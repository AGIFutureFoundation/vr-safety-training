#!/usr/bin/env node
/**
 * ECOSYSTEM — writes the Cognition.X blocks extract and the match table (docs/ecosystem.md).
 *
 *     node tools/eco_extract.mjs [path/to/cognition.x]      # default /home/user/agifuturefoundation/cognition.x
 *
 * Reads Cognition.X's data/blocks.csv from a local read-only clone (never fetched, never written), this repo's union and
 * trade stations (WebXR/packs/index.json → kinds "union" and "programme", audience "trades") and the robotics programme's
 * tracks (rp-programme-data.js), applies the declared rules in WebXR/shared/eco-blocks.js, and writes:
 *   WebXR/shared/eco-blocks-data.js   — the matched blocks only (the attributed extract, under 200 KB) and the match rows;
 *   docs/ecosystem/blocks-match.json  — the full match table, with every unmatched station and skill listed and why.
 * Deterministic: the same clone and the same rules give byte-identical files (no timestamps).
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CX = process.argv[2] || process.env.ECO_COGNITION_DIR || "/home/user/agifuturefoundation/cognition.x";
const imp = (rel) => import(pathToFileURL(join(ROOT, rel)).href);

/** RFC 4180 CSV → array of objects (quoted fields, doubled quotes, CRLF). */
export function ecoParseCsv(text) {
  const rows = []; let row = [], field = "", q = false;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { field += '"'; i += 1; } else q = false; } else field += c; continue; }
    if (c === '"') q = true; else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") { if (c === "\r" && text[i + 1] === "\n") i += 1; row.push(field); rows.push(row); row = []; field = ""; }
    else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const head = rows.shift();
  return rows.filter((r) => r.length === head.length).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

export function ecoStations(root = ROOT) {
  const idx = JSON.parse(readFileSync(join(root, "WebXR/packs/index.json"), "utf8"));
  const out = new Map();
  for (const p of idx.packs) {
    if (p.kind !== "union" && p.kind !== "programme") continue;
    const pk = JSON.parse(readFileSync(join(root, "WebXR/packs", p.file), "utf8"));
    if (pk.audience !== "trades") continue;
    for (const [id, name] of Object.entries(pk.stationNames ?? {})) if (!out.has(id)) out.set(id, { id, name, pack: p.id });
  }
  return [...out.values()];
}

async function main() {
  const csvPath = join(CX, "data/blocks.csv");
  if (!existsSync(csvPath)) { console.error(`no Cognition.X clone at ${CX}`); process.exit(2); }
  const ECO = await imp("WebXR/shared/eco-blocks.js");
  const RP = await imp("WebXR/shared/rp-programme-data.js");
  const blocks = ecoParseCsv(readFileSync(csvPath, "utf8"));
  const stations = ecoStations();
  const st = ECO.ecoMatchStations(stations, blocks);
  const sk = ECO.ecoMatchSkills(RP.RP_TRACKS, blocks);
  const used = new Set([...st.matched, ...sk.matched].flatMap((m) => m.blocks));
  const keep = ["block_id", "pack", "track", "grade", "level", "credential", "theme", "description", "transfer_check"];
  const extract = blocks.filter((b) => used.has(b.block_id)).map((b) => Object.fromEntries(keep.map((k) => [k, b[k]])))
    .sort((a, b) => (a.block_id < b.block_id ? -1 : 1));
  const provenance = {
    source: "github.com/agifuturefoundation/cognition.x", commit: ECO.ECO_SOURCE.commit, file: "data/blocks.csv",
    licence: "CC BY 4.0 (content; LICENSE-CONTENT). Cognition.X code is Apache-2.0 (LICENSE); no code is copied here.",
    attribution: "Blocks from Cognition.X (agifuturefoundation/cognition.x, commit 47c1820), licensed CC BY 4.0. Extracted, unmodified, by tools/eco_extract.mjs.",
    changes: "Only the matched rows; columns code and the empty fields kept as in the source; no text edited.",
    rules: "WebXR/shared/eco-blocks.js ECO_RULES and ECO_RP_RULES",
  };
  const data = {
    provenance,
    stations: st.matched, skills: sk.matched, blocks: extract,
    unmatchedCount: st.unmatched.length + sk.unmatched.length,
    counts: { stations: stations.length, stationsMatched: st.matched.length, skills: sk.matched.length + sk.unmatched.length, skillsMatched: sk.matched.length, excludedK12Skills: sk.excluded.length, blocks: extract.length },
  };
  const js = `// GENERATED by tools/eco_extract.mjs — do not edit by hand (ECOSYSTEM, docs/ecosystem.md).\n// ${provenance.attribution}\n// Licence: ${provenance.licence}\nexport const ECO_BLOCKS_DATA = ${JSON.stringify(data)};\n`;
  writeFileSync(join(ROOT, "WebXR/shared/eco-blocks-data.js"), js);
  mkdirSync(join(ROOT, "docs/ecosystem"), { recursive: true });
  const table = { provenance, counts: data.counts, stations: { matched: st.matched, unmatched: st.unmatched }, skills: sk };
  writeFileSync(join(ROOT, "docs/ecosystem/blocks-match.json"), JSON.stringify(table, null, 1) + "\n");
  console.log(`stations ${st.matched.length}/${stations.length} matched, ${st.unmatched.length} unmatched; skills ${sk.matched.length}/${sk.matched.length + sk.unmatched.length} (K-12 level excluded: ${sk.excluded.length}); extract ${extract.length} blocks, ${Buffer.byteLength(js)} bytes`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
