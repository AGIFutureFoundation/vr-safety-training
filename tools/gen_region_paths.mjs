/**
 * Region paths: for each mapped region, a short ordered route a learner can follow
 * through the training the region already offers.
 *
 *     node tools/gen_region_paths.mjs
 *
 * Built from docs-free inputs the repo already has: the region training table
 * (WebXR/shared/region-training-data.js, from tools/gen_region_training.mjs). Each
 * path is at most three steps, in this order:
 *
 *   1. a K-12 entry (the first K-12 station or track the region names), if any
 *   2. a trade programme (the first union programme the region's sites offer)
 *   3. a robot programme (the first robot programme the region offers), if any
 *
 * Nothing is invented: a step is only an id the region table already lists.
 * Regions without a robot programme simply have a shorter path, and
 * tools/check_region_paths.mjs reports how many.
 *
 * Writes, deterministically (no timestamps):
 *   WebXR/shared/region-paths-data.js   the paths, for the bundles
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const REGION_PATHS_FILE = join(ROOT, "WebXR", "shared", "region-paths-data.js");

/** The path for one region row. Pure: takes the table row, returns the steps. */
export function regionPath(row) {
  const steps = [];
  const k12 = row.k12Stations.length ? row.k12Stations[0] : row.k12[0];
  if (k12) steps.push({ kind: "k12", id: k12 });
  const trade = row.programmes.find((p) => !p.startsWith("k12-") && !row.robot.includes(p));
  if (trade) steps.push({ kind: "programme", id: trade });
  if (row.robot.length) steps.push({ kind: "robot", id: row.robot[0] });
  return { id: row.id, name: row.name, steps };
}

/** Every region's path, sorted by region id. */
export async function buildRegionPaths() {
  const { REGION_TRAINING } = await import(pathToFileURL(join(ROOT, "WebXR", "shared", "region-training-data.js")).href);
  return REGION_TRAINING.map(regionPath).sort((a, b) => a.id.localeCompare(b.id));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const paths = await buildRegionPaths();
  writeFileSync(
    REGION_PATHS_FILE,
    `// Region paths (generated by tools/gen_region_paths.mjs). One ordered route per mapped region:\n` +
      `// K-12 entry, trade programme, robot programme, each only if the region offers it. Do not edit by hand.\n` +
      `export const REGION_PATHS = ${JSON.stringify(paths, null, 2)};\n`,
  );
  const withRobot = paths.filter((p) => p.steps.some((s) => s.kind === "robot")).length;
  console.log(`Wrote ${REGION_PATHS_FILE.replace(ROOT + "/", "")} — ${paths.length} regions, ${withRobot} with a robot step.`);
}
