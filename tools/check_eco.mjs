const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const imp = (abs) => import(pathToFileURL(abs).href);
const read = (rel) => { try { return readFileSync(join(ROOT, rel), "utf8"); } catch (_) { return ""; } };
const SIB = process.env.ECO_SIBLINGS || "/home/user/agifuturefoundation";
let passed = 0, failed = 0, skipped = 0;
function ok(c, m) { if (!c) throw new Error(m); }
async function check(name, fn) {
  try { const r = await fn(); if (r === "SKIP") { skipped += 1; console.log(`SKIP ${name}`); return; } passed += 1; console.log(`PASS ${name}${r ? ` — ${r}` : ""}`); }
  catch (e) { failed += 1; console.log(`FAIL ${name} — ${e.message}`); }
}

