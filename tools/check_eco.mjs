#!/usr/bin/env node
/**
 * ECOSYSTEM — the seams with SmartCiti.X and Cognition.X (docs/ecosystem.md). Single checker; headless, no browser.
 *   1. the Cognition.X extract: provenance (source, commit 47c1820, CC BY 4.0, attribution line) in the data module and the
 *      match table, under 200 KB, every block referenced by a match present and every block present referenced;
 *   2. the match rules are deterministic: re-matching the extract's own blocks gives the committed rows (top-k of a superset
 *      restricted to its top-k is the same), twice, in shuffled input order; and with a read-only Cognition.X clone present,
 *      tools/eco_extract.mjs's matcher over the full dataset gives the committed table byte for byte (skipped without one);
 *   3. adults only: no block outside ECO_ADULT_BANDS reaches a match unless its rule names the band with a reason (none do),
 *      the robotics awareness / K-12 level is never mapped, and a planted K-12 block is refused by the matcher;
 *   4. the bus adapter: every event it emits validates against SmartCiti.X's documented shapes (bus/bus.mjs, telemetry.mjs,
 *      audit.mjs at 398f287), N of N, over a seeded hive day, governor decisions, arena rows and learner events; ineligible
 *      sessions (demo, signed out, K-12, no adult attestation, not opted in) emit nothing; affect never leaves; dedupe; skew;
 *      revoke deletes. With a read-only SmartCiti.X clone present, the messages also go through its real Bus (strict) and
 *      envelope(), and the audit entries through its AuditLog (skipped without one; nothing of it is copied);
 *   5. 0 network calls (fetch, XMLHttpRequest, WebSocket, sendBeacon stubbed to count) and no network API in the eco sources;
 *   6. Router.X is marked absent ("not yet built") in docs/ecosystem.md, and the instructor tab is wired read-only.
 */
import { readFileSync, existsSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const imp = (abs) => import(pathToFileURL(abs).href);
const read = (rel) => { try { return readFileSync(join(ROOT, rel), "utf8"); } catch (_) { return ""; } };
const SIB = process.env.ECO_SIBLINGS || "/home/user/agifuturefoundation";
let passed = 0, failed = 0, skipped = 0;
function ok(c, m) { if (!c) throw new Error(m); }
async function check(name, fn) {
  try { const r = await fn(); if (r === "SKIP") { skipped += 1; console.log(`SKIP ${name}`); return; } passed += 1; console.log(`PASS ${name}${r ? ` — ${r}` : ""}`); }
  catch (e) { failed += 1; console.log(`FAIL ${name} — ${e.message}`); }
}

// Count every network attempt from here on.
let network = 0;
const netStub = () => { network += 1; throw new Error("network call refused in check_eco"); };
globalThis.fetch = netStub;
globalThis.XMLHttpRequest = function () { netStub(); };
globalThis.WebSocket = function () { netStub(); };
try { Object.defineProperty(globalThis, "navigator", { value: { ...(globalThis.navigator ?? {}), sendBeacon: netStub }, configurable: true }); } catch (_) { /* read-only navigator: fetch, XHR and WebSocket still counted */ }

const ECO = await imp(join(ROOT, "WebXR/shared/eco-blocks.js"));
const BUS = await imp(join(ROOT, "WebXR/shared/eco-bus.js"));
const DATA = (await imp(join(ROOT, "WebXR/shared/eco-blocks-data.js"))).ECO_BLOCKS_DATA;
const TABLE = JSON.parse(read("docs/ecosystem/blocks-match.json") || "null");

await check("1. extract provenance, size and closure", () => {
  ok(DATA && TABLE, "data module or match table missing");
  for (const p of [DATA.provenance, TABLE.provenance]) {
    ok(p.commit === "47c18207bd2ef3295c66fac80aa7005bd8a7f6b9", "source commit");
    ok(/CC BY 4\.0/.test(p.licence) && /Apache-2\.0/.test(p.licence), "licence line");
    ok(/Cognition\.X/.test(p.attribution) && /CC BY 4\.0/.test(p.attribution) && /47c1820/.test(p.attribution), "attribution line");
  }
  const src = read("WebXR/shared/eco-blocks-data.js");
  ok(/^\/\/ GENERATED by tools\/eco_extract\.mjs/.test(src) && src.includes(DATA.provenance.attribution), "the data module's header carries the attribution");
  const bytes = statSync(join(ROOT, "WebXR/shared/eco-blocks-data.js")).size;
  ok(bytes < 200 * 1024, `extract ${bytes} bytes ≥ 200 KB`);
  const ids = new Set(DATA.blocks.map((b) => b.block_id));
  const used = new Set([...DATA.stations, ...DATA.skills].flatMap((m) => m.blocks));
  for (const u of used) ok(ids.has(u), `${u} referenced but not in the extract`);
  for (const i of ids) ok(used.has(i), `${i} in the extract but unused`);
  ok(TABLE.stations.unmatched.length + TABLE.skills.unmatched.length === DATA.unmatchedCount, "unmatched count");
  ok(TABLE.stations.unmatched.every((u) => u.station && u.why), "every unmatched station listed with a reason");
  return `${DATA.blocks.length} blocks, ${(bytes / 1024).toFixed(1)} KB; stations ${DATA.counts.stationsMatched}/${DATA.counts.stations}, skills ${DATA.counts.skillsMatched}/${DATA.counts.skills}, unmatched listed ${DATA.unmatchedCount}`;
});

const RP = await imp(join(ROOT, "WebXR/shared/rp-programme-data.js"));
const EX = await imp(join(ROOT, "tools/eco_extract.mjs"));
await check("2. match rules deterministic (extract re-match, shuffled, twice)", () => {
  const stations = EX.ecoStations(ROOT);
  const blocks = DATA.blocks;
  let seed = 7; const rnd = () => ((seed = (seed * 1103515245 + 12345) >>> 0) / 2 ** 32);
  const shuffle = (a) => a.map((x) => [rnd(), x]).sort((p, q) => p[0] - q[0]).map((p) => p[1]);
  const a = ECO.ecoMatchStations(stations, blocks), b = ECO.ecoMatchStations(shuffle(stations), shuffle(blocks));
  ok(JSON.stringify(a) === JSON.stringify(b), "station matching depends on input order");
  ok(JSON.stringify(a.matched) === JSON.stringify(DATA.stations), "re-matching the extract does not give the committed station rows");
  const s1 = ECO.ecoMatchSkills(RP.RP_TRACKS, shuffle(blocks));
  ok(JSON.stringify(s1.matched) === JSON.stringify(DATA.skills), "skill rows differ");
  return `${a.matched.length} station rows and ${s1.matched.length} skill rows reproduced`;
});

const CX = join(SIB, "cognition.x");
await check("2b. full re-extract from the read-only Cognition.X clone is byte-identical", () => {
  if (!existsSync(join(CX, "data/blocks.csv"))) return "SKIP";
  const blocks = EX.ecoParseCsv(readFileSync(join(CX, "data/blocks.csv"), "utf8"));
  const st = ECO.ecoMatchStations(EX.ecoStations(ROOT), blocks);
  const sk = ECO.ecoMatchSkills(RP.RP_TRACKS, blocks);
  ok(JSON.stringify(st.matched) === JSON.stringify(TABLE.stations.matched) && JSON.stringify(st.unmatched) === JSON.stringify(TABLE.stations.unmatched), "stations differ from the committed table — run node tools/eco_extract.mjs");
  ok(JSON.stringify(sk) === JSON.stringify(TABLE.skills), "skills differ from the committed table");
  return `${blocks.length} source blocks`;
});

await check("3. adults only: no school band on an adult path unless the rule states it", () => {
  for (const b of DATA.blocks) ok(ECO.ecoIsAdultBand(b.grade), `${b.block_id} grade ${b.grade} reached the extract`);
  for (const r of ECO.ECO_RULES) ok(!r.k12Band || r.k12Reason, `rule ${r.id} admits ${r.k12Band} without a reason`);
  ok(!DATA.skills.some((s) => s.skill.endsWith("/aware")), "awareness / K-12 level mapped");
  ok(TABLE.skills.excluded.length === RP.RP_TRACKS.length && TABLE.skills.excluded.every((e) => e.skill.endsWith("/aware")), "every track's awareness level listed as excluded");
  const planted = [{ block_id: "CX-K12-9999", pack: "Trade School", grade: "9–10", theme: "Rigging & Signals", credential: "Rigger", description: "Compute a lift and signal it" }];
  const rule = ECO.ECO_RULES.find((r) => r.id === "rigging");
  ok(ECO.ecoRank("crane lift rigging signal", planted, rule).length === 0, "a planted school-band block was ranked");
  ok(ECO.ecoRank("crane lift rigging signal", planted, { ...rule, k12Band: "9–10" }).length === 0, "a band without a reason was admitted");
  ok(ECO.ecoRank("crane lift rigging signal", planted, { ...rule, k12Band: "9–10", k12Reason: "fixture" }).length === 1, "an explicitly stated band should be admitted");
  return `${DATA.blocks.length}/${DATA.blocks.length} extract blocks in an adult band; planted K-12 refused`;
});

const SC = join(SIB, "smartciti.x");
await check("4. bus adapter: every event valid against the documented shapes", async () => {
  const OH = await imp(join(ROOT, "WebXR/shared/oh-hive.js"));
  const VB = await imp(join(ROOT, "WebXR/shared/vb-governor.js"));
  let t = Date.parse("2026-10-12T19:00:00.000Z");
  const bus = BUS.ecoBus({ consent: { demo: false, signedIn: true, k12: false, adult: true, optedIn: true }, clock: () => (t += 1000), sessionId: "s-eco-1" });
  // hive day (seeded) — every event; governor decisions from the hive's own governor-checked commands
  const day = OH.ohHiveDay(3, { ticksPerDay: 160 });
  for (const ev of day.events) bus.hive(ev);
  const gov = VB.vbGovernor({});
  const base = { clientId: "eco-c1", policyId: "vb-scripted-expert", siteId: "rb-site-soma-robot-cell", taskType: "rb-cell-entry", speed: 0.1, nearestPersonM: 6, agentId: "oh-dispatcher" };
  const cmds = [{ ...base, jobId: "j1", target: { kind: "sim", robotId: "rb-site-soma-robot-cell:cell" } },
    { ...base, jobId: "j2", target: { kind: "physical", robotId: "rb-site-soma-robot-cell:cell" } },
    { ...base, jobId: "j3", siteId: "nowhere", target: { kind: "sim", robotId: "r" } }];
  for (const c of cmds) { const d = gov.check(c); const r = bus.governor(d, c); ok(r.ok, `governor decision not recorded: ${r.reason}`); }
  for (const row of [{ modelId: "bc", scenarioId: "rb-cell-entry", k: 50, n: 60, lo: 0.72, hi: 0.91 }, { modelId: "dagger", scenarioId: "rb-cobot-zone-setup", k: 41, n: 60 }]) ok(bus.arena(row).ok, "arena row");
  const kinds = ["start", "step-ok", "step-wrong", "hint", "complete", "fail", "pause", "resume", "quit", "control"];
  kinds.forEach((kind, i) => ok(bus.learner({ learnerId: "lr-7f3a9c21", kind, station: "electrical", skills: ["loto"], seq: i, latencyMs: 900 + i, ts: new Date(t).toISOString(), payload: { affect: "frustrated", mood: "busy", name: "x" } }).ok, `learner ${kind}`));
  // skew: a client clock an hour off is replaced by the receipt time
  const sk = bus.learner({ learnerId: "lr-7f3a9c21", kind: "complete", station: "electrical", seq: 99, ts: "2026-10-12T17:00:00.000Z" });
  ok(sk.message.payload.ts_source === "server", "skewed client clock trusted");
  // dedupe
  ok(bus.learner({ learnerId: "lr-7f3a9c21", kind: "complete", station: "electrical", seq: 99, ts: "2026-10-12T17:00:00.000Z" }).duplicate, "duplicate not deduped");
  const msgs = bus.messages(), aud = bus.audit();
  let bad = 0;
  for (const m of msgs) { const p = BUS.ecoValidateMessage(m); if (p.length) { bad += 1; throw new Error(`message ${m.event_id}: ${p.join("; ")}`); } }
  for (const a of aud) { const p = BUS.ecoValidateAudit(a); if (p.length) { bad += 1; throw new Error(`audit ${a.seq}: ${p.join("; ")}`); } }
  ok(msgs.every((m) => !("affect" in m.payload.payload) && !("mood" in m.payload.payload) && !("name" in m.payload.payload)), "affect, mood or a name left in a payload");
  ok(bus.signalsUsable("lr-7f3a9c21").usable && !bus.signalsUsable("lr-nobody00").usable, "the three-event floor");
  ok(aud.some((a) => a.action === "governor.refuse") && aud.some((a) => a.action === "governor.allow-sim"), "both governor outcomes recorded");
  ok(bus.stats.physical === 0, "physical");
  const n = msgs.length + aud.length;
  // ineligible sessions emit nothing
  for (const c of [{}, { demo: true, signedIn: true, k12: false, adult: true, optedIn: true }, { demo: false, signedIn: false, k12: false, adult: true, optedIn: true }, { demo: false, signedIn: true, k12: true, adult: true, optedIn: true }, { demo: false, signedIn: true, k12: false, adult: false, optedIn: true }, { demo: false, signedIn: true, k12: false, adult: true, optedIn: false }]) {
    const b2 = BUS.ecoBus({ consent: c });
    ok(!b2.learner({ learnerId: "lr-7f3a9c21", kind: "start", station: "electrical" }).ok && b2.messages().length === 0, `ineligible session emitted: ${JSON.stringify(c)}`);
  }
  ok(!bus.learner({ learnerId: "someone@example.org", kind: "start" }).ok, "an email accepted as a learner id");
  // live cross-check against SmartCiti.X's own modules (read-only clone; imported, never copied)
  let live = "no SmartCiti.X clone: documented shapes only";
  if (existsSync(join(SC, "bus/bus.mjs"))) {
    const SB = await imp(join(SC, "bus/bus.mjs")), ST = await imp(join(SC, "bus/telemetry.mjs")), SA = await imp(join(SC, "bus/audit.mjs"));
    ok(SB.TOPIC_OWNERS[BUS.ECO_TOPIC] === BUS.ECO_TOPIC_ROLE && SB.SCHEMA_VERSION === BUS.ECO_SCHEMA_VERSION, "topic owner or schema version drifted");
    ok(JSON.stringify(ST.VERBS) === JSON.stringify(BUS.ECO_VERBS) && ST.MAX_CLOCK_SKEW_MS === BUS.ECO_MAX_SKEW_MS && ST.MIN_USABLE_EVENTS === BUS.ECO_MIN_USABLE, "telemetry constants drifted");
    const real = new SB.Bus({ strict: true }); let got = 0; real.subscribe(BUS.ECO_TOPIC, "lpa", () => { got += 1; });
    for (const m of msgs) { const r = real.publish(m.topic, m.role, m.payload, { event_id: m.event_id, schema_version: m.schema_version }); ok(r.ok, "real bus refused"); }
    ok(got === msgs.length, "real bus delivered fewer");
    const e = ST.envelope({ learner_id: "lr-7f3a9c21", session_id: "s", verb: "completed", context: {}, payload: {}, ts: new Date().toISOString() });
    ok(Object.keys(e).join() === BUS.ECO_ENVELOPE_KEYS.join() && Object.keys(e.context).join() === BUS.ECO_CONTEXT_KEYS.join(), "envelope keys differ from the real envelope()");
    const sig = ST.extractSignals(msgs.map((m) => m.payload)); ok(sig.usable, "the real extractSignals found the window unusable");
    const log = new SA.AuditLog({ clock: () => 0 });
    for (const a of aud) { const r = log.append(a); ok(Object.keys(r).join() === BUS.ECO_AUDIT_KEYS.join(), "real AuditLog entry keys differ"); }
    ok(ST.toXapi(msgs[0].payload) !== null, "toXapi");
    live = `also accepted by SmartCiti.X's real Bus (${msgs.length}/${msgs.length}), envelope() keys, extractSignals and AuditLog (${aud.length}/${aud.length})`;
  }
  // revoke deletes
  ok(bus.revoke().remaining === 0 && bus.messages().length === 0 && !bus.learner({ learnerId: "lr-7f3a9c21", kind: "start", station: "x", seq: 500 }).ok, "revoke did not delete or stop");
  return `${n - bad}/${n} events valid (${msgs.length} telemetry messages, ${aud.length} audit entries: hive ${day.events.length}, governor 3, arena 2); ${live}`;
});

await check("5. 0 network calls; no network API in the eco sources", () => {
  for (const f of ["WebXR/shared/eco-blocks.js", "WebXR/shared/eco-bus.js", "WebXR/shared/eco-blocks-data.js", "tools/eco_extract.mjs"]) {
    const s = read(f).replace(/^\s*(\/\/|\*).*$/gm, "");
    ok(!/\bfetch\s*\(|XMLHttpRequest|new WebSocket|sendBeacon|EventSource|https?:\/\/(?!github\.com)/.test(s), `${f} names a network API`);
    ok(!/localStorage|indexedDB|sessionStorage/.test(s), `${f} touches storage`);
  }
  ok(network === 0, `${network} network calls`);
  return "network 0";
});

await check("6. Router.X marked absent; instructor tab wired read-only; bundles and prefix", () => {
  const doc = read("docs/ecosystem.md");
  ok(/Router\.X/.test(doc) && /no Router\.X repository/i.test(doc) && /not yet built/i.test(doc), "docs/ecosystem.md must say no Router.X repository exists and mark its interface not yet built");
  const html = read("WebXR/instructor/index.html"), app = read("WebXR/instructor/js/app.js"), bundle = read("tools/bundle_webxr.py");
  ok(html.includes('id="tab-eco"') && html.includes('id="eco-root"'), "tab markup");
  ok(app.includes("ecoMountBlocksPanel") && app.includes('["eco", "tab-eco", "view-eco"]'), "app wiring");
  ok(bundle.indexOf('"eco-blocks-data.js"') > 0 && bundle.indexOf('"eco-blocks-data.js"') < bundle.indexOf('"eco-blocks.js"'), "bundle order");
  for (const f of ["WebXR/shared/eco-blocks.js", "WebXR/shared/eco-bus.js"]) {
    const s = read(f);
    ok(!/import\s*\{[^}]*\bas\b/.test(s), `${f} uses an import alias`);
    for (const m of s.matchAll(/^(?:export\s+)?(?:const|let|var|function)\s+([A-Za-z_$][\w$]*)/gm)) ok(/^(eco|ECO_)/.test(m[1]), `${f}: top-level ${m[1]} lacks the prefix`);
  }
  // the panel, on a stub DOM
  const node = (tag) => ({ tag, children: [], className: "", txt: "", get textContent() { return this.txt; }, set textContent(v) { this.txt = v; if (v === "") this.children = []; }, attrs: {}, value: "", listeners: {},
    append(...c) { this.children.push(...c); if (tag === "select" && !this.value && c[0]?.value) this.value = c[0].value; }, setAttribute(k, v) { this.attrs[k] = v; }, addEventListener(t, f) { this.listeners[t] = f; } });
  const p = ECO.ecoMountBlocksPanel(node("div"), { doc: { createElement: node } });
  ok(p.pick.children.length === DATA.stations.length + DATA.skills.length && p.list.children.length > 0, "panel rows");
  p.pick.value = "electrical"; p.pick.listeners.change();
  ok(p.list.children.length === ECO.ecoNextBlocks("electrical").length && p.list.children.length > 0, "panel shows next blocks for a station");
  const check = read("tools/check_all.mjs"), base = read("docs/perf/checkers-baseline.json");
  ok(check.includes('"check_eco.mjs"') && base.includes('"check_eco.mjs"'), "check_all and the baseline row");
  return `panel ${p.pick.children.length} options; electrical → ${ECO.ecoNextBlocks("electrical").map((b) => b.block_id).join(", ")}`;
});

console.log(`\ncheck_eco: ${passed} passed, ${failed} failed, ${skipped} skipped`);
process.exit(failed ? 1 : 0);
