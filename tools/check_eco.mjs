#!/usr/bin/env node
/**
 * ECOSYSTEM — the seams with SmartCiti.X and Cognition.X (docs/ecosystem.md). Single checker; legs 1–6 headless, leg 7 in a browser.
 *   1. the Cognition.X extract: provenance (source, commit 47c1820, CC BY 4.0, attribution line) in the data module and the
 *      match table, under 200 KB, every block referenced by a match present and every block present referenced;
 *   2. the match rules are deterministic: re-matching the extract's own blocks gives the committed rows (top-k of a superset
 *      restricted to its top-k is the same), twice, in shuffled input order; and with a read-only Cognition.X clone present,
 *      tools/eco_extract.mjs's matcher over the full dataset gives the committed table byte for byte (skipped without one);
 *   3. adults only: no block outside ECO_ADULT_BANDS reaches a match unless its rule names the band with a reason (none do),
 *      the robotics awareness / K-12 level is never mapped, and a planted K-12 block is refused by the matcher;
 *   4. the bus adapter: every event it emits validates against SmartCiti.X's documented shapes (bus/bus.mjs, telemetry.mjs,
 *      audit.mjs at 398f287), N of N, over a seeded hive day, governor decisions, arena rows and learner events; ineligible
 *      sessions (demo, signed out, K-12, no adult attestation, not opted in) emit nothing; affect never leaves; dedupe; skew;
 *      revoke deletes. With a read-only SmartCiti.X clone present, the messages also go through its real Bus (strict) and
 *      envelope(), and the audit entries through its AuditLog (skipped without one; nothing of it is copied);
 *   5. 0 network calls (fetch, XMLHttpRequest, WebSocket, sendBeacon stubbed to count) and no network API in the eco sources;
 *   6. Router.X is marked absent ("not yet built") in docs/ecosystem.md, and the instructor tab is wired read-only;
 *   7. the Ecosystem tab in the BUILT instructor page (Playwright): options and blocks as in the extract, 0 page errors,
 *      0 requests and 0 storage writes after the click (skipped, saying so, only without Playwright);
 *   8. the learner path (eco-learn.js): a real game.js Session under the real dx-data.js consent gate holds every event,
 *      valid, only for an opted-in adult; 0 signed out, demo, not opted in or K-12; 0 after dxRevoke, even mid-run.
 *   9. the same path in the BUILT smartcity page (Playwright): a real station stepped under a real opt-in holds start + each
 *      step, every event valid, 0 once consent is removed; 0 when not opted in, in the demo and on a K-12 surface.
 */
import { readFileSync, existsSync, statSync } from "node:fs";
