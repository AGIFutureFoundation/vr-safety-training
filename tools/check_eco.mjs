const RP = await imp(join(ROOT, "WebXR/shared/rp-programme-data.js"));
const EX = await imp(join(ROOT, "tools/eco_extract.mjs"));
await check("2. match rules deterministic (extract re-match, shuffled, twice)", () => {
  const stations = EX.ecoStations(ROOT);
  const blocks = DATA.blocks;
  let seed = 7; const rnd = () => ((seed = (seed * 1103515245 + 12345) >>> 0) / 2 ** 32);
  const shuffle = (a) => a.map((x) => [rnd(), x]).sort((p, q) => p[0] - q[0]).map((p) => p[1]);
  const a = ECO.ecoMatchStations(stations, blocks), b = ECO.ecoMatchStations(shuffle(stations), shuffle(blocks));
  ok(JSON.stringify(a) === JSON.stringify(b), "station matching depends on input order");
  ok(JSON.stringify(a.matched) === JSON.stringify(DATA.stations), "re-matching the extract does not give the committed station rows");
  const s1 = ECO.ecoMatchSkills(RP.RP_TRACKS, shuffle(blocks));
  ok(JSON.stringify(s1.matched) === JSON.stringify(DATA.skills), "skill rows differ");
  return `${a.matched.length} station rows and ${s1.matched.length} skill rows reproduced`;
});

