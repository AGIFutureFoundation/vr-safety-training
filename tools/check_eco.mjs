globalThis.fetch = netStub;
globalThis.XMLHttpRequest = function () { netStub(); };
globalThis.WebSocket = function () { netStub(); };
try { Object.defineProperty(globalThis, "navigator", { value: { ...(globalThis.navigator ?? {}), sendBeacon: netStub }, configurable: true }); } catch (_) { /* read-only navigator: fetch, XHR and WebSocket still counted */ }

const ECO = await imp(join(ROOT, "WebXR/shared/eco-blocks.js"));
