/**
 * Region training map: for every mapped region, which union programmes, K-12
 * tracks and robot programmes its sites offer, and which unions train there.
 *
 *     node tools/gen_region_training.mjs
 *
 * Read from what the regions already say — each WebXR/shared/np-data-*.js
 * region's sites (their `programmes` and `trades`) and its field lessons —
 * checked against the catalog (WebXR/smartcity/catalog.json) and the unions
 * registry (tools/unions.json). Nothing is invented: a region lists only ids
 * the catalog and registry already hold. Anything that does not resolve is
 * listed as `unresolved`, never dropped, so tools/check_region_training.mjs
 * can fail on it.
 *
 * Writes, deterministically (no timestamps):
 *   WebXR/shared/region-training-data.js   the table, for the bundles
 *   docs/region-training.md                the same table, readable
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SHARED = join(ROOT, "WebXR", "shared");
export const REGION_TRAINING_FILE = join(SHARED, "region-training-data.js");
export const REGION_TRAINING_DOC = join(ROOT, "docs", "region-training.md");

// The robot programmes a region's robotics training is counted against. A
// programme joins this list only by being a robot-control or robot-operations
// programme in the catalog; an id not in the catalog is reported, not counted.
export const ROBOT_PROGRAMMES = ["robot-control-basics", "aerospace-defense-and-robotics", "warehouse-and-logistics-automation"];

const catalog = JSON.parse(readFileSync(join(ROOT, "WebXR", "smartcity", "catalog.json"), "utf8"));
const registry = JSON.parse(readFileSync(join(ROOT, "tools", "unions.json"), "utf8"));
const unionList = Array.isArray(registry) ? registry : registry.unions ?? Object.values(registry);

export const REGION_CATALOG = {
  programmes: new Set(catalog.curricula.map((c) => c.id)),
  unions: new Set(unionList.map((u) => u.id)),
};

/** Loads every region export: the first export of each np-data-*.js module. */
export async function loadRegions(dir = SHARED) {
  const files = readdirSync(dir).filter((f) => /^np-data-.*\.js$/.test(f)).sort();
  const regions = [];
  for (const f of files) {
    const mod = await import(pathToFileURL(join(dir, f)).href);
    const region = Object.values(mod)[0];
    if (region && Array.isArray(region.sites)) regions.push({ file: f, region });
  }
  return regions;
}

/** One region's row. Pure: the catalog and the regions come in as arguments. */
export function regionRow({ file, region }, cat = REGION_CATALOG) {
  const programmes = new Set();
  const unions = new Set();
  const unresolvedProgrammes = new Set();
  const unresolvedUnions = new Set();
  let sitesWithProgrammes = 0;
  for (const site of region.sites) {
    const ids = site.programmes ?? [];
    if (ids.length) sitesWithProgrammes += 1;
    for (const id of ids) {
      if (cat.programmes.has(id)) programmes.add(id);
      else unresolvedProgrammes.add(id);
    }
    for (const id of site.trades ?? []) {
      if (cat.unions.has(id)) unions.add(id);
      else unresolvedUnions.add(id);
    }
  }
  const k12 = [...programmes].filter((id) => id.startsWith("k12-")).sort();
  const robot = [...programmes].filter((id) => ROBOT_PROGRAMMES.includes(id)).sort();
  return {
    id: region.id,
    name: region.name,
    region: region.region,
    file,
    sites: region.sites.length,
    sitesWithProgrammes,
    programmes: [...programmes].sort(),
    k12,
    robot,
    unions: [...unions].sort(),
    fieldLessons: (region.fieldLessons ?? []).length,
    unresolved: {
      programmes: [...unresolvedProgrammes].sort(),
      unions: [...unresolvedUnions].sort(),
    },
  };
}

/** The whole table, sorted by region id so the output is stable. */
export async function buildRegionTraining() {
  const regions = await loadRegions();
  return regions.map((r) => regionRow(r)).sort((a, b) => a.id.localeCompare(b.id));
}

function writeAll(rows) {
  const data = `// Region training map (console REGION-TRAINING, generated by tools/gen_region_training.mjs).\n` +
    `// One row per mapped region: the programmes and unions its sites offer, the K-12 tracks,\n` +
    `// and the robot programmes. Do not edit by hand.\n` +
    `export const REGION_TRAINING = ${JSON.stringify(rows, null, 2)};\n`;
  writeFileSync(REGION_TRAINING_FILE, data);

  const lines = [
    "# Region training map",
    "",
    "Generated by `tools/gen_region_training.mjs` from each region's sites, checked against the catalog and the unions registry.",
    "",
    "| Region | Sites with training | Programmes | K-12 tracks | Robot programmes | Unions | Field lessons |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const r of rows) {
    lines.push(`| ${r.name} (${r.id}) | ${r.sitesWithProgrammes} of ${r.sites} | ${r.programmes.length} | ${r.k12.length} | ${r.robot.length} | ${r.unions.length} | ${r.fieldLessons} |`);
  }
  lines.push("");
  writeFileSync(REGION_TRAINING_DOC, lines.join("\n"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const rows = await buildRegionTraining();
  writeAll(rows);
  const programmes = rows.reduce((n, r) => n + r.programmes.length, 0);
  console.log(`Wrote ${REGION_TRAINING_FILE.replace(ROOT + "/", "")} — ${rows.length} regions, ${programmes} region-programme links.`);
}
