#!/usr/bin/env node
// OMEGA-CLAW (docs/consoles/OMEGA-CLAW.md): run the declared protocol (OC_PROTOCOL, committed before this ran) ONCE on
// the held-out seeds 7121–7180 through ROBO-ARENA's arena, exercise the refusal probes, run the persistent world with the
// promoted models, and write the record:
//   docs/evals/claw.json              the measured record (declarations, runs, verdicts, promotions, refusals, chain, world)
//   WebXR/shared/oc-claw-record.js    the same record as a module, for the read-only panels (OC_RECORD)
// Usage: node tools/claw_eval.mjs [--world-minutes 960] [--dry]   (--dry prints and writes nothing)
//        node tools/claw_eval.mjs --module-only   (rewrites the page module from docs/evals/claw.json; runs nothing)
// No network, no API, no key. Robots are simulated; the arena has no physical path.
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import * as ra from "../WebXR/shared/ra-arena.js";
import { ocClaw, ocRaAdapter, ocProtocolDeclarations, ocHash, OC_PROTOCOL, OC_PROTOCOL_2, OC_AGENTS, OC_VERSION } from "../WebXR/shared/oc-claw.js";
import { ocWorld } from "../WebXR/shared/oc-world.js";
import { VB_TASKS } from "../WebXR/shared/vb-shared-data.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const arg = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const WORLD_MINUTES = Number(arg("--world-minutes", 960));
const DRY = args.includes("--dry");

/**
 * The page's copy of each record: no per-run leaderboards (the panel ranks from the results), no result hashes, and the
 * chain trimmed to its head ({ lines, hash }) plus its last line, which the page re-hashes. The full chain stays in
 * docs/evals/claw.json and claw2.json, and check_claw re-walks it there.
 */
function ocSlim(record) {
  const chain = record.chain ?? [];
  const { chain: _c, ...rest } = record;
  return { ...rest, runs: record.runs.map((r) => ({ declId: r.declId, scenarioId: r.scenarioId, seeds: r.seeds, results: r.results.map(({ resultHash, family, ...x }) => x) })), chainHead: { lines: chain.length, hash: chain.length ? chain[chain.length - 1].hash : "genesis" }, chainTail: chain.slice(-1) };
}
function ocWriteModule(record) {
  let r2 = null;
  try { r2 = JSON.parse(readFileSync(join(ROOT, "docs/evals/claw2.json"), "utf8")); } catch (_) { r2 = null; }
  const s1 = ocSlim(record), s2 = r2 ? ocSlim(r2) : null;
  writeFileSync(join(ROOT, "WebXR/shared/oc-claw-record.js"), `// OMEGA-CLAW: the measured records of the declared protocols (generated by tools/claw_eval.mjs; do not edit by hand).\n// SmartCiti.X Holodeck · Powered by AGI Corp. Simulated robots, measured once on held-out seeds; see docs/evals/claw.json and claw2.json.\n// Each chain is trimmed to its head hash, line count and last line; the full chains are in those files.\nexport const OC_RECORD_1 = ${JSON.stringify(s1)};\nexport const OC_RECORD_2 = ${JSON.stringify(s2)};\nexport const OC_RECORDS = [OC_RECORD_1, OC_RECORD_2].filter(Boolean);\nexport const OC_RECORD = OC_RECORDS[OC_RECORDS.length - 1];\n`);
}
if (args.includes("--module-only")) { ocWriteModule(JSON.parse(readFileSync(join(ROOT, "docs/evals/claw.json"), "utf8"))); console.log("wrote WebXR/shared/oc-claw-record.js from docs/evals/claw.json and claw2.json"); process.exit(0); }
if (arg("--protocol", "1") === "2" || args.includes("--dev")) { await ocRunProtocol2({ dev: args.includes("--dev") }); process.exit(0); }

/**
 * Protocol 2 (round 7): OC_PROTOCOL_2 ONCE on ARENA-2's declared seeds 7181–7240, in a NEW claw whose held-out set is
 * those seeds only; then its three probes, a world with the promoted models, and docs/evals/claw2.json.
 * `--dev` is the stub run: the same flow on development seeds 1–20 (declared as that claw's held-out set), writing nothing.
 */
async function ocRunProtocol2({ dev = false } = {}) {
  const { raTexts, raStations, RA_DEV_SEEDS } = await import("./arena_eval.mjs");
  const P = dev ? { ...OC_PROTOCOL_2, seeds: RA_DEV_SEEDS } : OC_PROTOCOL_2;
  if (!dev) {
    const decl = JSON.parse(readFileSync(join(ROOT, OC_PROTOCOL_2.seedSource.file), "utf8"));
    const [a, b] = String(decl.protocol.seeds.gym).split("–").map(Number);
    if (a !== P.seeds[0] || b !== P.seeds[P.seeds.length - 1] || b - a + 1 !== P.seeds.length) throw new Error(`protocol 2 seeds do not match ${OC_PROTOCOL_2.seedSource.file} (${decl.protocol.seeds.gym})`);
    if (args.includes("--dry")) throw new Error("--dry is not offered for protocol 2: a held-out run happens once");
  }
  const envs = await raStations();
  const lmOptions = { texts: raTexts(), stationFor: (sc) => envs[sc] ?? null };
  const arena = ocRaAdapter(ra, { lmOptions });
  const claw = ocClaw({ arena, heldOut: P.seeds });
  const decls = ocProtocolDeclarations(P);
  const t0 = Date.now();
  for (const d of decls) { const r = claw.declare(d); if (!r.ok) throw new Error(`declaration refused: ${d.id} ${r.reason}`); }
  for (const d of decls) claw.train(d.id);
  for (const d of decls) { const r = claw.evaluate(d.id); if (!r.ok) throw new Error(`run refused: ${d.id} ${r.reason}`); }
  for (const d of decls) claw.promote(d.id);
  const before = claw.runs().length;
  const [q1, q2, q3] = P.probes;
  const p1 = claw.evaluate(q1.id);
  const d2 = claw.declare({ id: q2.id, scenarioId: q2.scenarioId, models: q2.models, incumbent: q2.incumbent, challengers: q2.challengers, metric: "success", seeds: dev ? P.seeds.slice(0, 10) : q2.seeds });
  const p2 = claw.evaluate(q2.id);
  const p3 = claw.declare({ id: q3.id, scenarioId: q3.scenarioId, models: q3.models, incumbent: q3.incumbent, challengers: q3.challengers, metric: "success", seeds: q3.seeds });
  const probes = [{ kind: "undeclared", refused: !p1.ok, reason: p1.reason ?? null }, { kind: "seed-reused", declared: d2.ok, refused: !p2.ok, reason: p2.reason ?? null, reused: p2.refusal?.reused ?? null }, { kind: "not-held-out", refused: !p3.ok, reason: p3.reason ?? null, seeds: "7121–7130 (protocol 1's, spent)" }, { kind: "runs-added-by-probes", n: claw.runs().length - before }];
  const audit = claw.auditAll();
  const evalMs = Date.now() - t0;
  const promotedNow = claw.promoted();
  const promoted = Object.fromEntries(Object.keys(VB_TASKS).map((sc) => [sc, promotedNow[sc] ?? P.incumbent]));
  const policyFor = (modelId, sc, env, seed) => { const b = ra.raBuild(modelId, sc, { lmOptions }); return b?.policyFor ? b.policyFor(seed) : null; };
  const world = ocWorld({ seed: 2, promoted, policyFor });
  world.run(dev ? 120 : WORLD_MINUTES);
  const ws = world.stats();
  const comparisons = claw.verdicts(), promotions = claw.promotions(), refusals = claw.refusals();
  const lm = (sc) => { const r = claw.runs().find((x) => x.scenarioId === sc); const g = (id) => r?.results.find((x) => x.modelId === id); return { scenarioId: sc, lm: g("ra-lm") ? `${g("ra-lm").k}/${g("ra-lm").n}` : "n/a", lmCi: g("ra-lm")?.ci ?? null, lmRuleBreaks: g("ra-lm")?.ruleBreaks ?? null, bc: g("bc") ? `${g("bc").k}/${g("bc").n}` : "n/a", bcCi: g("bc")?.ci ?? null, bcRuleBreaks: g("bc")?.ruleBreaks ?? null, verdict: comparisons.find((c) => c.scenarioId === sc && c.challenger === "ra-lm")?.verdict ?? null }; };
  const record = {
    schema: "smartcitix.holodeck.omega-claw@1", version: OC_VERSION,
    protocol: { version: P.version, hash: ocHash(OC_PROTOCOL_2), seedSource: P.seedSource, scenarios: P.scenarios, models: P.models, incumbent: P.incumbent, incumbentFrom: P.incumbentFrom, challengers: P.challengers, negativeControl: P.negativeControl, lm: P.lm, seeds: `${P.seeds[0]}–${P.seeds[P.seeds.length - 1]} (${P.seeds.length})`, metric: P.metric, interval: P.interval, promotion: P.promotion },
    measured: true, simulated: true, dev,
    arena: { version: ra.RA_VERSION, governor: ra.RA_GOVERNOR, note: "ra-lm is ROBO-ARENA's ra/1 small language-conditioned model (trained here), built with its declared texts and station tasks; ARENA-2's ra-lm-h is not in this branch" },
    agents: OC_AGENTS.map((a) => ({ id: a.id, name: a.name, role: a.role, label: a.label, avatar: a.avatar })),
    declarations: claw.declarations().map((d) => ({ id: d.id, scenarioId: d.scenarioId, models: d.models, incumbent: d.incumbent, challengers: d.challengers, negativeControl: d.negativeControl, metric: d.metric, seeds: d.seeds.length, seedRange: `${d.seeds[0]}–${d.seeds[d.seeds.length - 1]}`, hash: d.hash })),
    runs: claw.runs().map((r) => ({ declId: r.declId, scenarioId: r.scenarioId, seeds: r.seeds.length, results: r.results, leaderboard: r.leaderboard })),
    comparisons, promotions, refusals, probes, audit, promoted: promotedNow,
    smallModel: P.scenarios.map(lm),
    counts: {
      declaredComparisons: comparisons.length, comparisonsRunOnce: comparisons.filter((c) => claw.runs().some((r) => r.declId === c.declId)).length,
      promotions: promotions.length, promotionsClear: promotions.filter((p) => p.cCi[0] > p.iCi[1] && p.ruleBreaks === 0 && p.governorChecked === p.steps && p.physical === 0).length,
      refusalsByReason: refusals.reduce((m, r) => ({ ...m, [r.reason]: (m[r.reason] ?? 0) + 1 }), {}),
      exercised: { undeclared: refusals.some((r) => r.reason === "undeclared"), "seed-reused": refusals.some((r) => r.reason === "seed-reused"), "rule-broken": refusals.some((r) => r.reason === "rule-broken"), "not-held-out": refusals.some((r) => r.reason === "not-held-out") },
      episodes: claw.runs().reduce((a, r) => a + r.results.reduce((b, x) => b + x.n, 0), 0), stepsRun: claw.runs().reduce((a, r) => a + r.results.reduce((b, x) => b + x.steps, 0), 0), stepsChecked: claw.runs().reduce((a, r) => a + r.results.reduce((b, x) => b + x.governorChecked, 0), 0), physical: claw.runs().reduce((a, r) => a + r.results.reduce((b, x) => b + x.physical, 0), 0),
    },
    world: { seed: 2, minutes: ws.minutes, days: ws.day, completed: ws.completed, refused: ws.refused, vetoed: ws.vetoed, dispatched: ws.dispatched, dispatchedChecked: ws.dispatchedChecked, steps: ws.steps, stepsMonitored: ws.stepsMonitored, governorEveryStep: ws.governorEveryStep, physicalDispatched: ws.physicalDispatched, waitingSupervisor: ws.waitingSupervisor, promoted, models: ws.models, sites: ws.sites.map((s) => ({ siteId: s.siteId, name: s.name, completed: s.completed })) },
    chain: claw.log(),
  };
  const line = (k, v) => console.log(`EVAL${dev ? " (dev seeds 1–20, not a result)" : ""} ${k}: ${v}`);
  line("protocol 2 declared comparisons", `${record.counts.declaredComparisons}, run once ${record.counts.comparisonsRunOnce}/${record.counts.declaredComparisons}`);
  line("promotions", `${promotions.length} (clear ${record.counts.promotionsClear}/${promotions.length})`);
  line("refusals exercised", `${Object.values(record.counts.exercised).filter(Boolean).length}/4 ${JSON.stringify(record.counts.refusalsByReason)}`);
  line("episodes", `${record.counts.episodes}; governor ${record.counts.stepsChecked}/${record.counts.stepsRun}; physical ${record.counts.physical}`);
  for (const s of record.smallModel) line(`ra-lm vs bc ${s.scenarioId}`, `${s.lm} [${s.lmCi?.join("–")}] rb ${s.lmRuleBreaks} vs ${s.bc} [${s.bcCi?.join("–")}] rb ${s.bcRuleBreaks}: ${s.verdict}`);
  line("world", `${ws.minutes} min, ${ws.completed} jobs, governor ${ws.stepsMonitored}/${ws.steps}, physical ${ws.physicalDispatched}`);
  line("audit", `chain ${audit.chain.ok ? "intact" : "broken"} (${audit.chain.lines} lines), declared first ${audit.declaredFirst}, seeds once ${audit.seedOnce}, held-out only ${audit.heldOnly}`);
  console.log(`(eval ${evalMs} ms)`);
  if (!dev) { writeFileSync(join(ROOT, "docs/evals/claw2.json"), JSON.stringify(record, null, 1) + "\n"); console.log("wrote docs/evals/claw2.json"); }
}

const arena = ocRaAdapter(ra);
const claw = ocClaw({ arena });
const decls = ocProtocolDeclarations();
const t0 = Date.now();
for (const d of decls) {
  const r = claw.declare(d);
  if (!r.ok) throw new Error(`declaration refused: ${d.id} ${r.reason}`);
}
for (const d of decls) claw.train(d.id);
for (const d of decls) { const r = claw.evaluate(d.id); if (!r.ok) throw new Error(`run refused: ${d.id} ${r.reason}`); }
for (const d of decls) claw.promote(d.id);
// The probes: each must be refused, and neither runs anything.
const probes = [];
{
  const before = claw.runs().length;
  const p1 = claw.evaluate(OC_PROTOCOL.probes[0].id);
  const pd = OC_PROTOCOL.probes[1];
  const dec = claw.declare({ id: pd.id, scenarioId: pd.scenarioId, models: pd.models, incumbent: pd.incumbent, challengers: pd.challengers, metric: "success", seeds: pd.seeds });
  const p2 = claw.evaluate(pd.id);
  probes.push({ kind: "undeclared", refused: !p1.ok, reason: p1.reason ?? null }, { kind: "seed-reused", declared: dec.ok, refused: !p2.ok, reason: p2.reason ?? null, reused: p2.refusal?.reused ?? null }, { kind: "runs-added-by-probes", n: claw.runs().length - before });
}
const audit = claw.auditAll();
const evalMs = Date.now() - t0;

// The persistent world with the promoted model per hive scenario (the four job kinds the hive dispatches).
const promoted = Object.fromEntries(Object.keys(VB_TASKS).map((sc) => [sc, claw.promoted()[sc] ?? OC_PROTOCOL.incumbent]));
const policyFor = (modelId, sc, env, seed) => { const b = ra.raBuild(modelId, sc); return b?.policyFor ? b.policyFor(seed) : null; };
const world = ocWorld({ seed: 1, promoted, policyFor });
world.run(WORLD_MINUTES);
const ws = world.stats();

const comparisons = claw.verdicts();
const promotions = claw.promotions();
const refusals = claw.refusals();
const record = {
  schema: "smartcitix.holodeck.omega-claw@1", version: OC_VERSION, protocol: { version: OC_PROTOCOL.version, hash: ocHash(OC_PROTOCOL), scenarios: OC_PROTOCOL.scenarios, models: OC_PROTOCOL.models, incumbent: OC_PROTOCOL.incumbent, challengers: OC_PROTOCOL.challengers, negativeControl: OC_PROTOCOL.negativeControl, seeds: `${OC_PROTOCOL.seeds[0]}–${OC_PROTOCOL.seeds[OC_PROTOCOL.seeds.length - 1]} (${OC_PROTOCOL.seeds.length})`, metric: OC_PROTOCOL.metric, interval: OC_PROTOCOL.interval, promotion: OC_PROTOCOL.promotion },
  measured: true, simulated: true, arena: { version: ra.RA_VERSION, governor: ra.RA_GOVERNOR, note: "ra-lm is the contract stub in this branch (not applicable) until ROBO-ARENA's small model is merged" },
  agents: OC_AGENTS.map((a) => ({ id: a.id, name: a.name, role: a.role, label: a.label, avatar: a.avatar })),
  declarations: claw.declarations().map((d) => ({ id: d.id, scenarioId: d.scenarioId, models: d.models, incumbent: d.incumbent, challengers: d.challengers, negativeControl: d.negativeControl, metric: d.metric, seeds: d.seeds.length, seedRange: `${d.seeds[0]}–${d.seeds[d.seeds.length - 1]}`, hash: d.hash })),
  runs: claw.runs().map((r) => ({ declId: r.declId, scenarioId: r.scenarioId, seeds: r.seeds.length, results: r.results, leaderboard: r.leaderboard })),
  comparisons, promotions, refusals, probes, audit,
  promoted: claw.promoted(),
  counts: {
    declaredComparisons: comparisons.length, comparisonsRunOnce: comparisons.filter((c) => claw.runs().some((r) => r.declId === c.declId)).length,
    promotions: promotions.length, promotionsClear: promotions.filter((p) => p.cCi[0] > p.iCi[1] && p.ruleBreaks === 0 && p.governorChecked === p.steps && p.physical === 0).length,
    refusalsByReason: refusals.reduce((m, r) => ({ ...m, [r.reason]: (m[r.reason] ?? 0) + 1 }), {}),
    exercised: { undeclared: refusals.some((r) => r.reason === "undeclared"), "seed-reused": refusals.some((r) => r.reason === "seed-reused"), "rule-broken": refusals.some((r) => r.reason === "rule-broken") },
    episodes: claw.runs().reduce((a, r) => a + r.results.reduce((b, x) => b + x.n, 0), 0), stepsRun: claw.runs().reduce((a, r) => a + r.results.reduce((b, x) => b + x.steps, 0), 0), stepsChecked: claw.runs().reduce((a, r) => a + r.results.reduce((b, x) => b + x.governorChecked, 0), 0), physical: claw.runs().reduce((a, r) => a + r.results.reduce((b, x) => b + x.physical, 0), 0),
  },
  world: { seed: 1, minutes: ws.minutes, days: ws.day, completed: ws.completed, refused: ws.refused, vetoed: ws.vetoed, dispatched: ws.dispatched, dispatchedChecked: ws.dispatchedChecked, steps: ws.steps, stepsMonitored: ws.stepsMonitored, governorEveryStep: ws.governorEveryStep, physicalDispatched: ws.physicalDispatched, waitingSupervisor: ws.waitingSupervisor, promoted, models: ws.models, sites: ws.sites.map((s) => ({ siteId: s.siteId, name: s.name, completed: s.completed })) },
  chain: claw.log(),
};
const line = (k, v) => console.log(`EVAL ${k}: ${v}`);
line("declared comparisons", `${record.counts.declaredComparisons}, run once on held-out seeds ${record.counts.comparisonsRunOnce}/${record.counts.declaredComparisons}`);
line("promotions", `${record.counts.promotions} (clear interval, 0 rule breaks, governor on every step: ${record.counts.promotionsClear}/${record.counts.promotions})`);
line("refusals exercised", `${Object.values(record.counts.exercised).filter(Boolean).length}/3 ${JSON.stringify(record.counts.refusalsByReason)}`);
line("episodes", `${record.counts.episodes}; governor checked ${record.counts.stepsChecked}/${record.counts.stepsRun} steps; physical ${record.counts.physical}`);
line("world", `${ws.minutes} simulated minutes, ${ws.completed} jobs completed, governor ${ws.stepsMonitored}/${ws.steps} steps, physical dispatches ${ws.physicalDispatched}`);
line("audit", `chain ${audit.chain.ok ? "intact" : "broken"} (${audit.chain.lines} lines), declared first ${audit.declaredFirst}, seeds once ${audit.seedOnce}`);
line("promoted", JSON.stringify(record.promoted));
console.log(`(eval ${evalMs} ms)`);
if (!DRY) {
  writeFileSync(join(ROOT, "docs/evals/claw.json"), JSON.stringify(record, null, 1) + "\n");
  ocWriteModule(record);
  console.log("wrote docs/evals/claw.json and WebXR/shared/oc-claw-record.js");
}
